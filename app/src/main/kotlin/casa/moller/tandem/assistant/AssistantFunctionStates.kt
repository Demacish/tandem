package casa.moller.tandem.assistant

import android.content.Context
import android.os.Build
import android.util.Log
import androidx.annotation.RequiresApi
import androidx.appfunctions.AppFunctionManager
import androidx.appfunctions.AppFunctionName
import casa.moller.tandem.core.data.assistant.AssistantSettingsRepository
import casa.moller.tandem.core.data.di.ApplicationScope
import dagger.hilt.android.qualifiers.ApplicationContext
import javax.inject.Inject
import javax.inject.Singleton
import kotlin.coroutines.cancellation.CancellationException
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.flow.distinctUntilChanged
import kotlinx.coroutines.flow.map
import kotlinx.coroutines.launch

/**
 * Fas 5 (funktioner lane, plan §8.7): keeps the system's enabled state of Tandem's App Functions in
 * step with "Låt assistenten använda Tandem". The functions are declared disabled
 * ([BaseTandemAppFunctionService]), so an assistant does not even see them as usable until the user
 * turns the setting on; turning it off puts them back to that default. Runs once per process start
 * and on every change of the setting, only on Android 16 and newer, and only changes what differs.
 * The functions refuse by themselves while the setting is off, so a failed call here (for example
 * before the system has indexed a fresh install) costs nothing but the system's listing.
 */
@Singleton
class AssistantFunctionStates internal constructor(
    private val packageName: String,
    private val settings: AssistantSettingsRepository,
    private val scope: CoroutineScope,
    private val managerOf: () -> AppFunctionManager?,
) {
    @Inject
    constructor(
        @ApplicationContext context: Context,
        settings: AssistantSettingsRepository,
        @ApplicationScope scope: CoroutineScope,
    ) : this(context.packageName, settings, scope, { AppFunctionManager.getInstance(context) })

    /** Follows the setting from now on (the application scope's dispatcher, off the main thread). */
    fun start() {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.BAKLAVA) {
            scope.launch {
                settings.settings.map { it.enabled }.distinctUntilChanged().collect { enabled -> apply(enabled) }
            }
        }
    }

    // The system's App Function index can be missing or refuse (a fresh install, a profile); the
    // functions still refuse while the setting is off, so any failure is only logged.
    @RequiresApi(Build.VERSION_CODES.BAKLAVA)
    @Suppress("TooGenericExceptionCaught")
    private suspend fun apply(enabled: Boolean) {
        val manager = managerOf() ?: return
        try {
            val ids = functionIds()
            val names = ids.map { AppFunctionName(packageName, it) }
            val current = manager.getAppFunctionStates(names).associate { it.functionName.functionIdentifier to it.isEnabled }
            val wanted = if (enabled) AppFunctionManager.APP_FUNCTION_STATE_ENABLED else AppFunctionManager.APP_FUNCTION_STATE_DEFAULT
            ids.filter { current[it] != enabled }.forEach { manager.setAppFunctionEnabled(it, wanted) }
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            Log.w(TAG, "App Function states not updated: ${e.javaClass.simpleName}")
        }
    }

    internal companion object {
        private const val TAG = "TandemAssistant"

        /** Every function's id (`<class>#<function>`, generated by KSP). */
        @RequiresApi(Build.VERSION_CODES.BAKLAVA)
        fun functionIds(): List<String> = listOf(
            TandemAppFunctionService.FUNCTION_ID_ADD_TO_SHOPPING_LIST,
            TandemAppFunctionService.FUNCTION_ID_GET_SHOPPING_LIST,
            TandemAppFunctionService.FUNCTION_ID_GET_MEAL_PLAN,
            TandemAppFunctionService.FUNCTION_ID_SEARCH_RECIPES,
            TandemAppFunctionService.FUNCTION_ID_OPEN_RECIPE,
        )
    }
}
